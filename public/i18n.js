const LANGS = { fr: 'FR', wo: 'WO', ar: 'عربي' };
const ATTRS = ['placeholder', 'aria-label', 'title'];
let LANG = 'fr';
try { LANG = localStorage.getItem('lang') || 'fr'; } catch (e) {}
const ORIG = new WeakMap();

function tr(fr) {
  if (LANG === 'fr' || fr == null) return fr;
  const t = I18N[fr.trim()];
  if (!t) return fr;
  return fr.replace(fr.trim(), t[LANG === 'wo' ? 0 : 1]);
}
function translateNode(root) {
  if (!root) return;
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: n => n.parentElement && !n.parentElement.closest('script,style,.lang-switch,.leaflet-container') && n.nodeValue.trim() ? 1 : 2
  });
  let n;
  while ((n = w.nextNode())) {
    if (!ORIG.has(n)) ORIG.set(n, n.nodeValue);
    const v = tr(ORIG.get(n));
    if (n.nodeValue !== v) n.nodeValue = v;
  }
  if (!root.querySelectorAll) return;
  root.querySelectorAll('[placeholder],[aria-label],[title]').forEach(el => {
    if (el.closest('.lang-switch,.leaflet-container')) return;
    ATTRS.forEach(a => {
      if (!el.hasAttribute(a)) return;
      const k = 'data-fr-' + a;
      if (!el.hasAttribute(k)) el.setAttribute(k, el.getAttribute(a));
      const v = tr(el.getAttribute(k));
      if (el.getAttribute(a) !== v) el.setAttribute(a, v);
    });
  });
}
function applyLang() {
  // les <option> sans value gardent la valeur française envoyée au serveur
  document.querySelectorAll('option:not([value])').forEach(o => o.value = o.textContent);
  const html = document.documentElement;
  html.lang = LANG;
  html.dir = LANG === 'ar' ? 'rtl' : 'ltr';
  if (!html.dataset.frTitle) html.dataset.frTitle = document.title;
  const [p, s] = html.dataset.frTitle.split(' - ');
  document.title = s ? `${tr(p)} - ${tr(s)}` : tr(p);
  translateNode(document.body);
  document.querySelectorAll('.lang-switch button').forEach(b => b.classList.toggle('on', b.dataset.lang === LANG));
}
function setLang(l) { LANG = l; try { localStorage.setItem('lang', l); } catch (e) {} applyLang(); }

document.addEventListener('DOMContentLoaded', () => {
  const nav = document.querySelector('nav');
  if (nav && !nav.querySelector('.lang-switch')) {
    const d = document.createElement('div');
    d.className = 'lang-switch';
    d.setAttribute('role', 'group'); d.setAttribute('aria-label', 'Langue');
    d.innerHTML = Object.entries(LANGS).map(([k, v]) => `<button type="button" data-lang="${k}" lang="${k}">${v}</button>`).join('');
    d.onclick = e => { const b = e.target.closest('button'); if (b) setLang(b.dataset.lang); };
    const burger = nav.querySelector('.burger');
    burger ? nav.insertBefore(d, burger) : nav.appendChild(d);
  }
  applyLang();
  // traduit aussi le contenu chargé ensuite (événements, galerie, messages…)
  new MutationObserver(ms => {
    if (LANG === 'fr') return;
    ms.forEach(m => {
      if (m.type === 'characterData') return translateNode(m.target.parentElement);
      m.addedNodes.forEach(n => translateNode(n.nodeType === 1 ? n : n.parentElement));
    });
  }).observe(document.body, { childList: true, subtree: true });
});
